        قیمت نهایی محصول با توجه به قیمت طلا، اجرت ساخت، سود فروشنده و مالیات و سایر هزینه‌های قانونی مربوطه محاسبه می‌شود. جزئیات قابل درج در فاکتور خرید ارائه خواهد شد.

        ۴. ثبت سفارش
        ثبت سفارش در سایت به منزله ثبت درخواست خرید است. سفارش پس از تأیید پرداخت و بررسی موجودی و اطلاعات سفارش، نهایی خواهد شد.
