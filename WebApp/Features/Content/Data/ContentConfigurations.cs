        ۵. مسئولیت اطلاعات مشتری
        مشتری موظف است هنگام ثبت سفارش، اطلاعات صحیح و کامل مورد نیاز برای پردازش و تحویل سفارش را وارد نماید.
        مسئولیت ناشی از ثبت اطلاعات نادرست یا ناقص که موجب اختلال در پردازش یا تحویل سفارش شود، بر عهده مشتری خواهد بود.

